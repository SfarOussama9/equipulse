import pandas as pd
import random
import os
import google.generativeai as genai

# --- CONFIGURATION ---
# Set GEMINI_API_KEY in your environment (see .env.example)
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")

try:
    if not GEMINI_API_KEY:
        raise ValueError("GEMINI_API_KEY is not set")
    genai.configure(api_key=GEMINI_API_KEY)
    # Using gemini-2.0-flash based on available models
    model = genai.GenerativeModel('gemini-2.0-flash')
    USE_REAL_LLM = True
    print("✅ Gemini API Configured. Using Real LLM.")
except Exception as e:
    print(f"Gemini API not configured ({e}); using fallback templates.")
    print("   (Using fallback templates instead)")
    USE_REAL_LLM = False

# 1. Load Data
print("Loading inequity analysis...")
df = pd.read_csv("inequity_analysis.csv")

# Initialize Output File
output_file = "manager_action_plan.txt"
with open(output_file, "w", encoding="utf-8") as f:
    f.write("=== EQUILIBRIUM MANAGER CO-PILOT REPORT ===\nGenerated by AI\n\n")

# 2. Define the Co-Pilot Function
def generate_manager_recommendation(department, n_recommendations=5):
    header = f"\n--- ANALYZING DEPARTMENT: {department.upper()} ---"
    print(header)
    
    with open(output_file, "a", encoding="utf-8") as f:
        f.write(header + "\n")
    
    # Filter for this department
    dept_df = df[df["Department"] == department]
    
    if dept_df.empty:
        print("No data found for this department.")
        return

    # A. Find the "Crisis" Employees (High Burnout + Overloaded)
    # We prioritize "Hidden Heroes" first, then general high burnout cases
    if "Inequity_Flag" in dept_df.columns:
        crisis_candidates = dept_df[dept_df["Inequity_Flag"] == "Hidden Hero (Overworked)"].sort_values("Predicted_Burnout_Score", ascending=False)
        if crisis_candidates.empty:
             crisis_candidates = dept_df.sort_values("Predicted_Burnout_Score", ascending=False)
    else:
        crisis_candidates = dept_df.sort_values("Predicted_Burnout_Score", ascending=False)
        
    victims = crisis_candidates.head(n_recommendations)
    
    # B. Find "Savior" Employees (Low Burnout + Underutilized)
    # We get the pool of all potential saviors in the department first
    all_saviors = dept_df[
        (dept_df["Risk_Category"] == "Low") & 
        (dept_df["Workload_Profile"] == "Underutilized")
    ].sort_values("Weekly_Hours")
    
    used_saviors = []

    print(f"\n>>> GENERATING {len(victims)} AI RECOMMENDATIONS...\n")

    for i, (_, victim) in enumerate(victims.iterrows()):
        
        # --- STRATEGY 1: PEER SUPPORT (Same Role) ---
        # Try to find a savior with the SAME ROLE
        same_role_saviors = all_saviors[
            (all_saviors["Role"] == victim["Role"]) & 
            (~all_saviors["Employee_ID"].isin(used_saviors))
        ]
        
        peer_action = ""
        if not same_role_saviors.empty:
            savior = same_role_saviors.iloc[0]
            used_saviors.append(savior["Employee_ID"])
            peer_action = f"""
    ✅ OPTION A: WORKLOAD REBALANCING (Preferred)
    We identified {savior['Employee_ID']} ({savior['Role']}) as a perfect match for support.
    - Why: Same Role, Low Utilization ({savior['Weekly_Hours']} hrs/week).
    👉 Action: Reassign 1-2 active projects from {victim['Employee_ID']} to {savior['Employee_ID']}."""
        else:
            peer_action = f"""
    ⚠️ OPTION A: WORKLOAD REBALANCING
    No direct peer ({victim['Role']}) with capacity was found in the department.
    👉 Action: Consider cross-training a lower-level employee or opening a contractor requisition."""

        # --- STRATEGY 2: ALTERNATIVE SOLUTIONS (Context-Aware) ---
        alt_actions = []
        
        # Check for Meeting Overload
        if victim["Meeting_Hours"] > 15:
            alt_actions.append(f"- 📅 Meeting Detox: {victim['Employee_ID']} spends {victim['Meeting_Hours']}h in meetings. Audit recurring invites or enforce 'No-Meeting Wednesdays'.")
            
        # Check for Vacation Deficit
        if victim["Vacation_Days_Taken"] < 5:
            alt_actions.append(f"- 🏖️ Mandatory Leave: Employee has taken only {victim['Vacation_Days_Taken']} days off. Mandate a 3-day recharge break.")
            
        # Check for Project Overload
        if victim["Project_Count"] > 6:
            alt_actions.append(f"- 📉 Scope Reduction: Juggling {victim['Project_Count']} projects. Pause 2 non-critical initiatives immediately.")
            
        # Check for Isolation
        if "Peer_Support_Score" in victim and victim["Peer_Support_Score"] < 4:
             alt_actions.append(f"- 🤝 Mentorship: Peer support score is low. Schedule a skip-level 1:1 or assign a mentor.")

        if not alt_actions:
            alt_actions.append("- 🗣️ Retention Interview: Schedule a 1:1 to discuss career path and immediate stressors.")

        alt_action_text = "\n    ".join(alt_actions)

        # C. Generate the "LLM" Response
        if USE_REAL_LLM:
            prompt = f"""
            You are an expert HR Manager Co-Pilot. Write a sensitive, professional, and actionable email to a manager about an employee at risk of burnout.
            
            EMPLOYEE DETAILS:
            - ID: {victim['Employee_ID']}
            - Role: {victim['Role']}
            - Burnout Score: {victim['Predicted_Burnout_Score']}/10 (High Risk)
            - Workload: {victim['Workload_Profile']}, {victim['Weekly_Hours']} hours/week (Dept Avg: {victim['Dept_Avg_Hours']:.1f})
            
            SUGGESTED INTERVENTIONS:
            1. {peer_action}
            2. {alt_action_text}
            
            INSTRUCTIONS:
            - Subject line should be urgent but professional.
            - Tone: Empathetic, data-driven, and solution-oriented.
            - Structure: The Situation -> AI Suggested Actions -> Predicted Impact.
            - Keep it concise (under 200 words).
            """
            try:
                response = model.generate_content(prompt)
                recommendation = f"\n[{i+1}] (Generated by Gemini AI)\n{response.text}\n--------------------------------------------------"
            except Exception as e:
                print(f"⚠️ Gemini API Error: {e}. Using fallback.")
                recommendation = f"""
    [{i+1}] Subject: 🚨 Burnout Risk Alert: {victim['Role']} {victim['Employee_ID']}
    
    Hi Manager,
    
    Our AI has detected a critical burnout risk for {victim['Employee_ID']} ({victim['Role']}).
    
    📊 THE SITUATION:
    - Predicted Burnout Score: {victim['Predicted_Burnout_Score']}/10 (High Risk)
    - Workload Profile: {victim['Workload_Profile']}
    - Weekly Hours: {victim['Weekly_Hours']} (Dept Avg: {victim['Dept_Avg_Hours']:.1f})
    
    💡 AI SUGGESTED ACTIONS:
    {peer_action}
    
    ✅ OPTION B: IMMEDIATE INTERVENTIONS (Alternative)
    {alt_action_text}
    
    📉 PREDICTED IMPACT:
    Taking these actions is projected to reduce {victim['Employee_ID']}'s burnout score by ~1.5 points.
    --------------------------------------------------
        """
        else:
            recommendation = f"""
    [{i+1}] Subject: 🚨 Burnout Risk Alert: {victim['Role']} {victim['Employee_ID']}
    
    Hi Manager,
    
    Our AI has detected a critical burnout risk for {victim['Employee_ID']} ({victim['Role']}).
    
    📊 THE SITUATION:
    - Predicted Burnout Score: {victim['Predicted_Burnout_Score']}/10 (High Risk)
    - Workload Profile: {victim['Workload_Profile']}
    - Weekly Hours: {victim['Weekly_Hours']} (Dept Avg: {victim['Dept_Avg_Hours']:.1f})
    
    💡 AI SUGGESTED ACTIONS:
    {peer_action}
    
    ✅ OPTION B: IMMEDIATE INTERVENTIONS (Alternative)
    {alt_action_text}
    
    📉 PREDICTED IMPACT:
    Taking these actions is projected to reduce {victim['Employee_ID']}'s burnout score by ~1.5 points.
    --------------------------------------------------
        """
        print(recommendation)
        
        with open(output_file, "a", encoding="utf-8") as f:
            f.write(recommendation)

# 3. Run for a few departments
generate_manager_recommendation("Engineering", n_recommendations=3)
generate_manager_recommendation("Sales", n_recommendations=2)
